import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdir, mkdtemp, readFile, realpath, rm, writeFile } from 'node:fs/promises';
import { basename, dirname, join, resolve } from 'node:path';
import test, { before } from 'node:test';
import { promisify } from 'node:util';
import { approveJobValidation, listJobExecutions, observeOnce, prepareJobValidation, queueJobValidation, registerLocalSubscription, runApprovedJobsOnce } from '../dist/index.js';
import { JAVA_DOCKER_PROFILE, PYTHON_DOCKER_PROFILE } from '../dist/docker-runner.js';

const root = resolve(import.meta.dirname, '..');
const execute = promisify(execFile);
const hash = value => createHash('sha256').update(value).digest('hex');
const enginePath = join(root, 'work/tools/oasdiff/oasdiff');
const dockerOptions = { shell: false, timeout: 15_000, maxBuffer: 128 * 1024, encoding: 'utf8' };

before(async () => {
  assert.equal(process.platform, 'linux', 'This suite requires the dedicated Linux isolated-validation job.');
  for (const profile of [PYTHON_DOCKER_PROFILE, JAVA_DOCKER_PROFILE]) {
    await execute('docker', ['image', 'inspect', profile.image], dockerOptions);
  }
});

function contract(version) {
  const properties = version === 'A' ? { id: { type: 'string' }, amount_minor: { type: 'integer' }, currency: { type: 'string' } }
    : { id: { type: 'string' }, money: { type: 'object', required: ['value', 'currency'], properties: { value: { type: 'string' }, currency: { type: 'string' } } } };
  return { openapi: '3.0.3', info: { title: 'Synthetic local HTTP payments; not a commercial provider', version }, paths: {
    '/payments/{id}': { get: { operationId: 'getPayment', parameters: [{ in: 'path', name: 'id', required: true, schema: { type: 'string' } }], responses: {
      200: { description: 'Synthetic payment; USD minor units remain internal integers', content: Object.fromEntries(['application/json', 'application/xml'].map(media => [media,
        { schema: { type: 'object', required: Object.keys(properties), properties } }])) },
    } } },
  } };
}

async function fixture(t, language) {
  const parent = resolve(root, 'work/polyglot-integration');
  await mkdir(parent, { recursive: true });
  const actualParent = await realpath(parent);
  const directory = await mkdtemp(join(actualParent, 'case-'));
  t.after(async () => {
    const actual = await realpath(directory);
    assert.equal(dirname(actual), actualParent);
    assert(basename(actual).startsWith('case-'));
    await rm(actual, { recursive: true, force: false });
  });
  const consumerRoot = join(directory, 'consumer'), statePath = join(directory, 'state');
  await mkdir(consumerRoot);
  const file = language === 'python' ? 'payment_client.py' : 'PaymentClient.java';
  const originalTest = language === 'python' ? 'test_payment.py' : 'PaymentTest.java';
  const testPath = language === 'python' ? 'payment_contract_test.py' : 'PaymentContractTest.java';
  const before = await readFile(join(root, `dev/polyglot/${language}/baseline`, file), 'utf8');
  const after = await readFile(join(root, `dev/polyglot/${language}/candidate`, file), 'utf8');
  const tests = await readFile(join(root, `dev/polyglot/${language}`, originalTest), 'utf8');
  // Wrappers select the synthetic provider's B contract; the underlying tests and wrapper bytes are identical in both snapshots.
  const wrapper = language === 'python'
    ? 'import subprocess, sys, unittest\nfrom pathlib import Path\nclass PaymentContractTests(unittest.TestCase):\n    def test_unchanged_contract(self):\n        result = subprocess.run([sys.executable, "-B", str(Path(__file__).with_name("test_payment.py")), "B"], capture_output=True, text=True, timeout=10)\n        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)\n'
    : 'public class PaymentContractTest { public static void main(String[] args) throws Exception { PaymentTest.main(new String[] {"B"}); } }\n';
  for (const [path, bytes] of [[file, before], [originalTest, tests], [testPath, wrapper]]) await writeFile(join(consumerRoot, path), bytes);
  const sourcePath = join(directory, 'B.json'), baselinePath = join(directory, 'A.json');
  await writeFile(sourcePath, JSON.stringify(contract('B')));
  await writeFile(baselinePath, JSON.stringify(contract('A')));
  const subscription = await registerLocalSubscription({ statePath, sourcePath, baselinePath, consumerRoot, enginePath,
    providerBaseUrl: 'http://127.0.0.1:1', label: `Synthetic ${language} contract fixture` });
  const observed = await observeOnce({ statePath, enginePath, subscriptionId: subscription.id });
  assert.equal(observed.results[0].status, 'observed');
  const jobId = observed.results[0].jobId;
  const recipe = { schemaVersion: 1, summary: 'Operator-reviewed synthetic adapter, not generated by a real AI model.',
    decisions: [{ id: 'units', question: 'Are the decimal external amount and internal minor integer semantically equivalent?',
      answer: 'This synthetic fixture explicitly defines exact USD conversion; the unchanged tests cover large integers, unit corruption, malformed data, HTTP errors and bounded bodies.' }],
    files: [{ path: file, sha256: hash(before), edits: [{ before, after }] }] };
  return { directory, consumerRoot, statePath, jobId, recipe, testPaths: [testPath], before, after, file, tests, originalTest, wrapper, testPath };
}

for (const language of ['python', 'java']) {
  test(`${language}: the public SDK queues one explicit approval, baseline fails, candidate passes, and original tests stay intact`, { timeout: 90_000 }, async t => {
    const f = await fixture(t, language);
    const input = { statePath: f.statePath, jobId: f.jobId, recipe: f.recipe, testPaths: f.testPaths, enginePath };
    const request = await prepareJobValidation(input);
    assert.deepEqual(await prepareJobValidation(input), request, 'Repeated planning of immutable evidence must preserve the consent identity.');
    assert.equal(request.spec.profile.id, language === 'python' ? 'python313-linux-amd64-v1' : 'java25-linux-amd64-v1');
    assert.equal(request.plan.validation, 'not-run');
    assert.equal(request.plan.consumerExecuted, false);
    assert.deepEqual(await listJobExecutions({ statePath: f.statePath }), []);
    assert.deepEqual((await runApprovedJobsOnce({ statePath: f.statePath, enginePath })).results, []);
    await assert.rejects(queueJobValidation({ ...input, receiptId: '00000000-0000-4000-8000-000000000000' }), { code: 'INVALID_INPUT' });
    const receipt = await approveJobValidation({ ...input, expectedRequestId: request.id, origin: 'explicit-sdk-caller' });
    const queued = await queueJobValidation({ ...input, receiptId: receipt.id });
    assert.equal(queued.created, true);
    assert.equal((await queueJobValidation({ ...input, receiptId: receipt.id })).created, false);
    assert.equal(queued.intent.executionDigest, request.executionDigest);
    assert.equal(queued.intent.policyDigest, request.policyDigest);
    const cycle = await runApprovedJobsOnce({ statePath: f.statePath, enginePath, intentId: queued.intent.id });
    assert.equal(cycle.results.length, 1);
    const result = cycle.results[0];
    assert.equal(result.status, 'completed', JSON.stringify(result));
    assert.equal(result.outcome.status, 'improved', JSON.stringify(result));
    assert.equal(result.outcome.baseline.status, 'failed');
    assert.equal(result.outcome.candidate.status, 'passed', result.outcome.candidate.stderr);
    assert.equal(result.outcome.baseline.cleanup, 'removed');
    assert.equal(result.outcome.candidate.cleanup, 'removed');
    assert.equal(result.outcome.publication, 'not-authorized');
    const attempt = join(f.statePath, 'attempts', receipt.id);
    const detailed = JSON.parse(await readFile(join(attempt, 'result.json'), 'utf8'));
    assert.match(detailed.baseline.stderr, language === 'python' ? /KeyError: 'amount_minor'/u : /Expected amount_minor exactly once/u,
      'The baseline must fail because of the changed API contract, not missing runtime infrastructure.');
    for (const phase of ['baseline', 'candidate']) {
      assert.equal(await readFile(join(attempt, phase, f.originalTest), 'utf8'), f.tests);
      assert.equal(await readFile(join(attempt, phase, f.testPath), 'utf8'), f.wrapper);
      const journal = JSON.parse(await readFile(join(attempt, 'containers', `${phase}.intent.json`), 'utf8'));
      assert.equal(journal.profileSha256, hash(JSON.stringify(request.spec.profile)));
      await assert.rejects(execute('docker', ['container', 'inspect', journal.containerName], dockerOptions), error => error.code === 1 && /No such (?:object|container)/iu.test(error.stderr));
    }
    assert.equal(await readFile(join(f.consumerRoot, f.file), 'utf8'), f.before);
    assert.equal(await readFile(join(attempt, 'candidate', f.file), 'utf8'), f.after);
    assert.equal(await readFile(join(f.consumerRoot, f.originalTest), 'utf8'), f.tests);
    assert.deepEqual((await runApprovedJobsOnce({ statePath: f.statePath, enginePath, intentId: queued.intent.id })).results, [], 'An approval cannot execute twice.');
  });
  test(`${language}: a byte-valid recipe with invalid foreign syntax fails isolated compilation and never becomes a passing migration`, { timeout: 90_000 }, async t => {
    const f = await fixture(t, language);
    const malformed = language === 'python' ? 'def payment(:\n' : 'public class PaymentClient {\n';
    const recipe = { ...f.recipe, files: [{ path: f.file, sha256: hash(f.before), edits: [{ before: f.before, after: malformed }] }] };
    const input = { statePath: f.statePath, jobId: f.jobId, recipe, testPaths: f.testPaths, enginePath };
    const request = await prepareJobValidation(input);
    assert.equal(request.plan.validation, 'not-run');
    const receipt = await approveJobValidation({ ...input, expectedRequestId: request.id, origin: 'explicit-sdk-caller' });
    const queued = await queueJobValidation({ ...input, receiptId: receipt.id });
    const cycle = await runApprovedJobsOnce({ statePath: f.statePath, enginePath, intentId: queued.intent.id });
    assert.equal(cycle.results[0].status, 'completed');
    assert.equal(cycle.results[0].outcome.status, 'failed');
    assert.equal(cycle.results[0].outcome.candidate.status, 'failed');
    assert.equal(cycle.results[0].outcome.candidate.cleanup, 'removed');
    assert.equal(cycle.results[0].outcome.publication, 'not-authorized');
    const attempt = join(f.statePath, 'attempts', receipt.id);
    const detailed = JSON.parse(await readFile(join(attempt, 'result.json'), 'utf8'));
    assert.match(detailed.candidate.stderr, language === 'python' ? /SyntaxError/u : /reached end of file while parsing/u);
    assert.equal(await readFile(join(f.consumerRoot, f.file), 'utf8'), f.before);
    for (const phase of ['baseline', 'candidate']) {
      assert.equal(await readFile(join(attempt, phase, f.originalTest), 'utf8'), f.tests);
      assert.equal(await readFile(join(attempt, phase, f.testPath), 'utf8'), f.wrapper);
    }
  });
}
